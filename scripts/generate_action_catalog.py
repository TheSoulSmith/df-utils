#!/usr/bin/env python3
"""Generate the compact Rust action catalog from DiamondFire's actiondump."""

import json
import re
import sys
from pathlib import Path


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def ident(value: str) -> str:
    words = re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_")
    if not words:
        words = "Empty"
    if words[0].isdigit():
        words = f"N_{words}"
    return "".join(part.title() for part in words.split("_"))


def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(
            "usage: python3 scripts/generate_action_catalog.py "
            "<actiondump.json> [src/raw/catalog.rs]"
        )
    source = Path(sys.argv[1])
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(
        "src/raw/catalog.rs"
    )
    dump = json.loads(source.read_text())
    codeblocks = {entry["name"]: entry["identifier"] for entry in dump["codeblocks"]}
    records = []
    used_variants: set[str] = set()
    for action in dump["actions"]:
        block = codeblocks[action["codeblockName"]]
        base = f'{ident(block)}{ident(action["name"])}'
        alternatives = [[]]
        for argument in action["icon"].get("arguments", []):
            if "type" not in argument:
                alternatives.append([])
            elif argument["type"] != "NONE":
                alternatives[-1].append(argument)

        for alternative_index, arguments in enumerate(alternatives):
            preferred = (
                base
                if alternative_index == 0
                else f"{base}Alternative{alternative_index + 1}"
            )
            variant = preferred
            suffix = 1
            while variant in used_variants:
                variant = f"{preferred}Variant{suffix}"
                suffix += 1
            used_variants.add(variant)
            has_or_alternatives = len(alternatives) > 1
            records.append(
                (
                    variant,
                    block,
                    action,
                    arguments,
                    has_or_alternatives,
                    alternative_index + 1 if has_or_alternatives else 0,
                    len(alternatives),
                )
            )

    block_ids = sorted({entry["identifier"] for entry in dump["codeblocks"]})
    arg_types = sorted(
        {
            arg["type"]
            for _, _, _, args, _, _, _ in records
            for arg in args
        }
    )
    lines = [
        "// Generated by scripts/generate_action_catalog.py; do not edit by hand.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub enum BlockKind {",
        *(f"    {ident(block)}," for block in block_ids),
        "}",
        "",
        "impl BlockKind {",
        "    pub const fn as_wire(self) -> &'static str {",
        "        match self {",
        *(f"            Self::{ident(block)} => {rust_string(block)}," for block in block_ids),
        "        }",
        "    }",
        "",
        "    pub fn from_wire(value: &str) -> Option<Self> {",
        "        match value {",
        *(f"            {rust_string(block)} => Some(Self::{ident(block)})," for block in block_ids),
        "            _ => None,",
        "        }",
        "    }",
        "}",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub enum ArgKind {",
        *(f"    {ident(kind)}," for kind in arg_types),
        "}",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct ArgumentSpec {",
        "    pub kind: ArgKind,",
        "    pub optional: bool,",
        "    pub plural: bool,",
        "}",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct TagSpec {",
        "    pub name: &'static str,",
        "    pub default: &'static str,",
        "    pub slot: u8,",
        "    pub options: &'static [&'static str],",
        "}",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct ActionSpec {",
        "    pub block: BlockKind,",
        "    pub name: &'static str,",
        "    pub sub_action: &'static str,",
        "    pub has_or_alternatives: bool,",
        "    pub alternative_index: u8,",
        "    pub alternative_count: u8,",
        "    pub aliases: &'static [&'static str],",
        "    pub sub_action_blocks: &'static [BlockKind],",
        "    pub arguments: &'static [ArgumentSpec],",
        "    pub tags: &'static [TagSpec],",
        "    pub legacy_replacement: Option<&'static str>,",
        "    pub required_rank: &'static str,",
        "    pub requires_tokens: bool,",
        "    pub requires_sparks: bool,",
        "    pub requires_rank_and_tokens: bool,",
        "    pub advanced: bool,",
        "    pub world_exclusive: bool,",
        "}",
        "",
        "/// Action forms are keyed by both block kind and name. Each dump OR",
        "/// branch has its own enum variant and argument signature; the first",
        "/// branch uses the unsuffixed variant name, later ones use AlternativeN.",
        "#[repr(u16)]",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub enum Action {",
        *(f"    {variant}," for variant, _, _, _, _, _, _ in records),
        "}",
        "",
        "impl Action {",
        "    pub const ALL: &'static [Self] = &[",
        *(f"        Self::{variant}," for variant, _, _, _, _, _, _ in records),
        "    ];",
        "",
        "    pub const fn spec(self) -> &'static ActionSpec {",
        "        &ACTION_SPECS[self as usize]",
        "    }",
        "",
        "    pub fn from_wire(block: BlockKind, name: &str) -> Option<Self> {",
        "        Self::variants(block, name).next()",
        "    }",
        "",
        "    /// Return every typed argument form for a wire block/name pair.",
        "    pub fn variants(block: BlockKind, name: &str) -> impl Iterator<Item = Self> + '_ {",
        "        Self::ALL.iter().copied().filter(move |action| {",
        "            let spec = action.spec();",
        "            spec.block == block && spec.name == name",
        "        })",
        "    }",
        "}",
        "",
        "pub static ACTION_SPECS: &[ActionSpec] = &[",
    ]
    for (
        _,
        block,
        action,
        args,
        has_or_alternatives,
        alternative_index,
        alternative_count,
    ) in records:
        lines += [
            "    ActionSpec {",
            f"        block: BlockKind::{ident(block)},",
            f"        name: {rust_string(action['name'])},",
            f"        sub_action: {rust_string(action.get('subAction') or '')},",
            f"        has_or_alternatives: {str(has_or_alternatives).lower()},",
            f"        alternative_index: {alternative_index},",
            f"        alternative_count: {alternative_count},",
            f"        aliases: &[{', '.join(rust_string(alias) for alias in action.get('aliases', []))}],",
            "        sub_action_blocks: &["
            + ", ".join(
                f"BlockKind::{ident(block_id)}"
                for block_id in action.get("subActionBlocks", [])
            )
            + "],",
            "        arguments: &[",
        ]
        for arg in args:
            lines.append(
                "            ArgumentSpec { "
                f"kind: ArgKind::{ident(arg['type'])}, "
                f"optional: {str(arg['optional']).lower()}, "
                f"plural: {str(arg['plural']).lower()} "
                "},"
            )
        lines += ["        ],", "        tags: &["]
        for tag in action.get("tags", []):
            options = []
            for option in tag["options"]:
                options.append(rust_string(option["name"]))
                options.extend(rust_string(alias) for alias in option.get("aliases", []))
            lines += [
                "            TagSpec {",
                f"                name: {rust_string(tag['name'])},",
                f"                default: {rust_string(tag['defaultOption'])},",
                f"                slot: {tag['slot']},",
                f"                options: &[{', '.join(options)}],",
                "            },",
            ]
        replacement = action.get("legacyReplacement")
        if isinstance(replacement, dict):
            replacement = replacement.get("action")
        lines += [
            "        ],",
            f"        legacy_replacement: {f'Some({rust_string(replacement)})' if replacement else 'None'},",
            f"        required_rank: {rust_string(action['icon'].get('requiredRank', ''))},",
            f"        requires_tokens: {str(action['icon'].get('requireTokens', False)).lower()},",
            f"        requires_sparks: {str(action['icon'].get('requireSparks', False)).lower()},",
            f"        requires_rank_and_tokens: {str(action['icon'].get('requireRankAndTokens', False)).lower()},",
            f"        advanced: {str(action['icon'].get('advanced', False)).lower()},",
            f"        world_exclusive: {str(action['icon'].get('worldExclusive', False)).lower()},",
            "    },",
        ]
    lines += ["];"]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
